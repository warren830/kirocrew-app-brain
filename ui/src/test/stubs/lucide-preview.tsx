function draw(name: string, shape: ReactNode) {
  const Icon = ({ size = 24, style, className, ...rest }: IconProps) => (
    <svg xmlns="http://www.w3.org/2000/svg" width={size} height={size} viewBox="0 0 24 24" fill="none" stroke="currentColor" strokeWidth={2}
      strokeLinecap="round" strokeLinejoin="round" className={className} style={style as CSSProperties} aria-hidden={rest['aria-hidden']}
      aria-label={rest['aria-label']} data-icon={name}>
      {shape}
    </svg>
  )
  Icon.displayName = name
  return Icon
}

